#!/usr/bin/env python3
"""Publish the generated schema into a clone of the register. One command, so drift is cheap to fix.

Each artefact has exactly one source, which is the only arrangement that scales past two people:

``schema/misbehaviour-report-<v>.schema.json``
    **Generated from the model** in ``ifixai/register/spec.py``. Authored nowhere. This script
    copies the generated file into the register and writes a provenance note beside it recording the
    iFixAi version and the file's sha256, so the register can tell — with no network and no
    cross-repository CI — whether the schema it is validating against is the one it was published
    with.

``spec/report-spec-<v>.md``
    **Authored in the register**, and nowhere else. That is the page a citation lands on, so it
    belongs where the entries are. This repository's ``docs/register-spec.md`` is about the
    implementation and links to it rather than restating it; there is no copy to keep in step.

Usage::

    python scripts/publish_register_spec.py --registry ../agent-misbehavior-registry
    python scripts/publish_register_spec.py --registry ../agent-misbehavior-registry --check

``--check`` writes nothing and exits non-zero if the register's copy is out of date, which is what a
maintainer runs before a release.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from ifixai._version import VERSION  # noqa: E402
from ifixai.register.spec import SPEC_VERSION  # noqa: E402

SCHEMA_NAME = f"misbehaviour-report-{SPEC_VERSION}.schema.json"
SOURCE = ROOT / "ifixai" / "schemas" / SCHEMA_NAME
PROVENANCE_NAME = "PROVENANCE.md"

PROVENANCE = """\
# Where the schema came from

`{name}` is **generated**, never hand-edited. Its source is the report model in
[ifixai-ai/iFixAi](https://github.com/ifixai-ai/iFixAi), `ifixai/register/spec.py`, which is also
what the reference implementation validates against — so the schema an outside submitter checks
their file against and the rules the library enforces cannot disagree.

| | |
| --- | --- |
| Spec version | `{spec_version}` |
| Generated by | iFixAi `{ifixai_version}` |
| Published on | {published_on} |
| sha256 | `{digest}` |

`tools/test_tools.py` checks the file against the digest above on every pull request and every push,
so a schema edited here — or a copy that fell behind the model — fails rather than quietly changing
what the register accepts.

To republish after a change to the model:

```bash
# in a clone of ifixai-ai/iFixAi, beside a clone of this register
python scripts/generate_register_schema.py
python scripts/publish_register_spec.py --registry ../agent-misbehavior-registry
```

A change that would make an existing report mean something different is a **new spec version** with
its own schema file and its own spec document, never an edit of this one. Existing entries have to
keep meaning what they meant.
"""


def digest_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def provenance_text(digest: str, published_on: date) -> str:
    return PROVENANCE.format(
        name=SCHEMA_NAME,
        spec_version=SPEC_VERSION,
        ifixai_version=VERSION,
        published_on=published_on.isoformat(),
        digest=digest,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--registry", required=True, type=Path, help="A clone of the register.")
    parser.add_argument("--check", action="store_true", help="Report drift and write nothing.")
    arguments = parser.parse_args(argv)
    registry: Path = arguments.registry
    if not (registry / "registry.yaml").is_file():
        print(f"{registry} does not look like a clone of the register (no registry.yaml)", file=sys.stderr)
        return 2
    if not SOURCE.is_file():
        print(f"{SOURCE} is missing; run scripts/generate_register_schema.py first", file=sys.stderr)
        return 2

    target = registry / "schema" / SCHEMA_NAME
    provenance = registry / "schema" / PROVENANCE_NAME
    source_bytes = SOURCE.read_bytes()
    digest = hashlib.sha256(source_bytes).hexdigest()

    if arguments.check:
        if not target.is_file():
            print(f"{target} does not exist", file=sys.stderr)
            return 1
        if target.read_bytes() != source_bytes:
            print(
                f"{target} is out of date.\n"
                f"  the register has sha256 {digest_of(target)}\n"
                f"  the model generates    {digest}\n"
                "Run: python scripts/publish_register_spec.py --registry "
                f"{registry}",
                file=sys.stderr,
            )
            return 1
        if provenance.is_file() and digest not in provenance.read_text(encoding="utf-8"):
            print(f"{provenance} records a different digest than the schema beside it", file=sys.stderr)
            return 1
        print(f"{target.name} in {registry} matches the model ({digest[:12]})")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(source_bytes)
    provenance.write_text(provenance_text(digest, date.today()), encoding="utf-8")
    print(f"published {target} ({digest[:12]})")
    print(f"wrote {provenance}")
    print("Commit both in the register. The spec prose is authored there and is not copied.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
